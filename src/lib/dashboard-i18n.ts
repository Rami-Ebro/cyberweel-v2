export function translateDashboardText(value: string, lang: DashboardLang) {
  if (lang === "ar" || !value || !arabicPattern.test(value)) return value;

  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const normalized = value.trim();
  const exact = dashboardEnglish[normalized];
  if (exact) return `${leading}${exact}${trailing}`;

  for (const [pattern, formatter] of dashboardPatterns) {
    const match = normalized.match(pattern);
    if (match) return `${leading}${formatter(...match.slice(1))}${trailing}`;
  }

  return value;
}

export function hasUntranslatedDashboardArabic(value: string) {
  return arabicPattern.test(translateDashboardText(value, "en"));
}
